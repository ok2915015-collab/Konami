export function getTeamLogo(team: any): string {
  if (!team) return FALLBACK_LOGO;
  if (typeof team === "string") {
    const found = INITIAL_TEAMS.find(t => t.id === team || t.name?.toLowerCase() === team.toLowerCase());
    return found?.logo || FALLBACK_LOGO;
  }
  if (team.logo && typeof team.logo === "string" && team.logo.trim() !== "") {
    return team.logo;
  }
  const found = INITIAL_TEAMS.find(t => t.id === team.id || (t.name && team.name && t.name.toLowerCase() === team.name.toLowerCase()));
  return found?.logo || FALLBACK_LOGO;
}

export function getMergedTeams(firestoreTeams: any[] = []): any[] {
  const map = new Map<string, any>();
  
  // 1. Populate map with INITIAL_TEAMS as the baseline
  INITIAL_TEAMS.forEach(t => {
    map.set(t.id, { ...t, deleted: false });
  });

  // 2. Merge with firestoreTeams
  firestoreTeams.forEach(ft => {
    if (!ft) return;
    const key = ft.id || ft.docId;
    if (!key) return;

    if (ft.deleted === true) {
      map.delete(key);
      if (ft.name) {
        for (const [id, team] of map.entries()) {
          if (team.name && team.name.toLowerCase() === ft.name.toLowerCase()) {
            map.delete(id);
          }
        }
      }
      return;
    }

    const initialMatch = INITIAL_TEAMS.find(it => it.id === key || (it.name && ft.name && it.name.toLowerCase() === ft.name.toLowerCase()));
    
    if (initialMatch) {
      const mergedLogo = (ft.logo && typeof ft.logo === "string" && ft.logo.trim() !== "") 
        ? ft.logo 
        : initialMatch.logo;
      map.set(initialMatch.id, {
        ...initialMatch,
        ...ft,
        id: initialMatch.id,
        logo: mergedLogo || FALLBACK_LOGO,
        deleted: false
      });
    } else {
      map.set(key, {
        ...ft,
        id: key,
        logo: (ft.logo && typeof ft.logo === "string" && ft.logo.trim() !== "") ? ft.logo : FALLBACK_LOGO,
        deleted: false
      });
    }
  });

  return Array.from(map.values()).filter(t => !t.deleted);
}

